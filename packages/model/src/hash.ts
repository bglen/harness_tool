/** Deterministic JSON serialization (sorted keys) for hashing and byte-identical exports. */
export function stableStringify(value: unknown, indent?: number): string {
  // Only true cycles (an object inside itself) are errors; the same object referenced twice is fine.
  const stack = new Set<object>();
  const norm = (v: unknown): unknown => {
    if (v === null || typeof v !== "object") return v;
    if (stack.has(v as object)) throw new Error("cycle");
    stack.add(v as object);
    let out: unknown;
    if (Array.isArray(v)) out = v.map(norm);
    else {
      const o: Record<string, unknown> = {};
      for (const k of Object.keys(v as Record<string, unknown>).sort()) {
        const x = (v as Record<string, unknown>)[k];
        if (x !== undefined) o[k] = norm(x);
      }
      out = o;
    }
    stack.delete(v as object);
    return out;
  };
  return JSON.stringify(norm(value), null, indent);
}

/** Fast non-cryptographic 53-bit hash (cyrb53) → hex. Used for cache keys and design hashes shown in UI. */
export function quickHash(str: string, seed = 0): string {
  let h1 = 0xdeadbeef ^ seed;
  let h2 = 0x41c6ce57 ^ seed;
  for (let i = 0; i < str.length; i++) {
    const ch = str.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  const n = 4294967296 * (2097151 & h2) + (h1 >>> 0);
  return n.toString(16).padStart(14, "0");
}

